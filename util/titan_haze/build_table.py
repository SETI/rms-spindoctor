"""Build the simulator's table of Titan's haze against wavelength.

Usage::

    python util/titan_haze/build_table.py [<out.py>]

writes ``src/spindoctor/sim/render/bodies/titan_haze_table.py``, which the renderer
reads.  ``tests/util_titan_haze/test_build_table.py`` rebuilds the table and compares
it with the committed module.

Inputs, both published by the Huygens DISR team:

- ``disr_haze_phase_80_200km.tab`` beside this script: the haze's single-scattering
  phase function between 80 and 200 km, tabulated against scattering angle (rows,
  degrees) at the DISR wavelengths (columns, Angstrom), from Tomasko et al. (2008,
  Planet. Space Sci. 56, 669).
- :data:`ALBEDO_ABOVE_144_KM`: the haze's single-scattering albedo above 144 km,
  transcribed from Table 2 of the same paper.  The transcription has not been
  checked against the published table.

At each DISR wavelength from 430 to 1078 nm, the span over which both are given, the
phase function is normalized to average 1 over the sphere and fitted by a two-term
Henyey-Greenstein function ``(1 - f) HG(g) + f HG(g2)``, by least squares in its
logarithm, each tabulated scattering angle weighted by the span of angle it stands
for, so the dense rows near 0 and 180 deg do not outvote the sparse middle.  The
albedo is interpolated linearly in wavelength to the same wavelengths.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

HERE = Path(__file__).resolve().parent
PHASE_TABLE = HERE / 'disr_haze_phase_80_200km.tab'
OUT = HERE.parents[1] / 'src/spindoctor/sim/render/bodies/titan_haze_table.py'

# The DISR wavelengths fitted, nm: those from 430 to 1078 nm, where both the phase
# function and the albedo are tabulated.
WAVELENGTHS_NM = (430.0, 490.9, 599.9, 713.1, 822.4, 934.8, 1078.0)

# Table 2 of Tomasko et al. (2008): single-scattering albedo above 144 km, by
# wavelength in nm, as transcribed.  The rows at 934 and 938 nm are separate, and
# the rows at 670 and 675 nm carry the same value.  The transcription is unverified
# against the published table (#1197).
ALBEDO_ABOVE_144_KM = (
    (430.0, 0.8200),
    (491.0, 0.8700),
    (531.0, 0.9002),
    (555.0, 0.9105),
    (600.0, 0.9195),
    (634.0, 0.9250),
    (670.0, 0.9319),
    (675.0, 0.9319),
    (751.0, 0.9450),
    (830.0, 0.9600),
    (934.0, 0.9626),
    (938.0, 0.9550),
    (1078.0, 0.9500),
)


def henyey_greenstein(g: float, theta: np.ndarray) -> np.ndarray:
    """The Henyey-Greenstein function at scattering angle ``theta`` (rad), mean 1."""
    return (1.0 - g * g) / (1.0 + g * g - 2.0 * g * np.cos(theta)) ** 1.5


def fit_phase(deg: np.ndarray, phase: np.ndarray) -> tuple[float, float, float]:
    """Normalize a tabulated phase function and fit it with two HG terms.

    Returns:
        ``(g, g2, f)``.
    """
    theta = np.radians(deg)
    fine = np.radians(np.linspace(0.0, 180.0, 18001))
    fine_phase = np.exp(np.interp(fine, theta, np.log(phase)))
    phase = phase / (0.5 * np.trapezoid(fine_phase * np.sin(fine), fine))
    span = np.gradient(deg)
    weight = np.sqrt(span / span.sum())

    def residual(x: np.ndarray) -> np.ndarray:
        g, g2, f = x
        model = (1.0 - f) * henyey_greenstein(g, theta) + f * henyey_greenstein(g2, theta)
        return weight * (np.log(model) - np.log(phase))

    fit = least_squares(residual, [0.8, -0.2, 0.1], bounds=([0.0, -0.99, 0.0], [0.99, 0.99, 1.0]))
    g, g2, f = (float(x) for x in fit.x)
    return g, g2, f


def build_rows() -> list[tuple[float, float, float, float, float]]:
    """The table rows: wavelength (nm), g, g2, f, and albedo."""
    table = np.genfromtxt(PHASE_TABLE, names=True)
    deg = table['deg']
    columns = {float(name) / 10.0: name for name in table.dtype.names[1:]}
    albedo_nm, albedo = (np.array(column) for column in zip(*ALBEDO_ABOVE_144_KM, strict=True))
    rows = []
    for wavelength in WAVELENGTHS_NM:
        g, g2, f = fit_phase(deg, np.asarray(table[columns[wavelength]], dtype=np.float64))
        rows.append((wavelength, g, g2, f, float(np.interp(wavelength, albedo_nm, albedo))))
    return rows


def render_module(rows: list[tuple[float, float, float, float, float]]) -> str:
    """The text of the generated table module."""
    lines = [
        '"""Titan\'s haze against wavelength, generated by ``util/titan_haze/build_table.py``.',
        '',
        'Do not edit by hand: rerun the script.  Each row is a DISR wavelength in nm, the',
        'two-term Henyey-Greenstein fit ``(g, g2, f)`` to the haze phase function between 80',
        'and 200 km, and the single-scattering albedo above 144 km (Tomasko et al. 2008,',
        'Planet. Space Sci. 56, 669, its tabulated phase functions and Table 2).',
        '"""',
        '',
        "__all__ = ['TITAN_HAZE_ROWS']",
        '',
        'TITAN_HAZE_ROWS: tuple[tuple[float, float, float, float, float], ...] = (',
    ]
    for wavelength, g, g2, f, albedo in rows:
        lines.append(f'    ({wavelength:.1f}, {g:.4f}, {g2:.4f}, {f:.4f}, {albedo:.4f}),')
    lines += [')', '"""Rows of ``(wavelength_nm, g, g2, g2_fraction, albedo)``."""', '']
    return '\n'.join(lines)


def main() -> None:
    """Build and write the module."""
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.write_text(render_module(build_rows()))
    print(out)


if __name__ == '__main__':
    main()
