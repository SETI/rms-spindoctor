"""Titan's haze, defined once as a property of the body and a function of wavelength.

A body whose ``atmosphere`` block says ``haze_model: titan`` takes Titan's published haze
instead of explicit haze parameters.  Before the body is drawn,
:func:`resolve_model_atmosphere` turns the block into the explicit keys of
:mod:`spindoctor.sim.render.bodies.atmosphere`, evaluated over the scene filter's
solar-weighted passband (:mod:`spindoctor.sim.instruments.passbands`).

**The published haze.**

- *Vertical structure.*  Above 80 km the haze's extinction falls with a 65 km scale
  height to 140 km and a 45 km scale height above that (Tomasko et al. 2008, Planet.
  Space Sci. 56, 669; Doose et al. 2016, Icarus 270, 355).  The limb lies above 140
  km, so the rendered column is the exponential above it: scale height 45 km,
  referenced at 140 km.
- *Optical depth.*  The optical depth of the haze above 80 km is
  ``1.012e7 * lambda**-2.339`` at wavelength ``lambda`` in nm (Tomasko et al. 2008),
  2.66 at 650 nm.  Carried up to 140 km along the 65 km scale height and integrated
  along a line of sight tangent there through the 45 km scale height, that is a
  tangent optical depth of 14.3 at 140 km at 650 nm.  The extinction at 80 km is
  the published column over the 65 km scale height, as if that scale height held all
  the way up; since the haze above 140 km thins faster, with 45 km, the column above
  80 km comes to 0.88 of the published 2.66.  Scaling the extinction to keep the
  published total instead would raise the 650 nm tangent depth to 16.3 and lift the
  level of unit tangent optical depth about 6 km.  The scale heights are not
  reported to vary with wavelength, so only the optical depth does.
- *Albedo and phase function.*  At the DISR wavelengths from 430 to 1078 nm,
  ``titan_haze_table.py`` (generated by ``util/titan_haze/build_table.py``) holds the
  single-scattering albedo above 144 km and a two-term Henyey-Greenstein fit to the
  haze phase function between 80 and 200 km, both from Tomasko et al. (2008).  Between
  those wavelengths each quantity is interpolated linearly; beyond them it takes the
  end value.
- *Size.*  Titan's mean radius is 2575 km.  A body that sets ``km_per_pixel`` uses it;
  any other stands for Titan at its own size, its mean semi-axis in pixels being
  2575 km.

**Over a passband.**  Each quantity is averaged over the passband's solar-weighted
transmission.  The optical depth is averaged in its logarithm, since the limb's height
above the reference altitude is the scale height times that logarithm, and so the
average places the limb where the passband's light, on the whole, places it.  The
albedo and the phase-function terms are averaged directly.

**What the definition leaves out.**  Methane absorbs strongly in bands at 619, 727, and
889 nm (Karkoschka 1994, Icarus 111, 174), and through the windows between them the
surface can show.  Neither is rendered, so scene validation refuses a filter that
sees those bands' cores or puts too much of its light outside the table, which holds its
end values below 430 nm (see :mod:`spindoctor.sim.scene.rules_body`).
"""

from __future__ import annotations

import math
from collections.abc import Mapping
from dataclasses import dataclass, replace
from typing import Any

import numpy as np

from spindoctor.sim.instruments.passbands import Passband, solar_weighted_passband
from spindoctor.sim.render.bodies.titan_haze_table import TITAN_HAZE_ROWS
from spindoctor.sim.scene.truth_atmosphere import HAZE_MODEL_KEYS, TITAN_HAZE_MODEL
from spindoctor.sim.scene.truth_body import Body
from spindoctor.support.types import NDArrayFloatType

__all__ = [
    'TITAN_MEAN_RADIUS_KM',
    'TitanHaze',
    'effective_titan_haze',
    'resolve_model_atmosphere',
    'resolved_atmosphere_params',
    'tangent_depth_at_reference',
]

TITAN_MEAN_RADIUS_KM = 2575.0
"""Titan's mean radius, km."""

SCALE_HEIGHT_KM = 45.0
"""The haze's extinction scale height above 140 km (Doose et al. 2016)."""

REFERENCE_ALTITUDE_KM = 140.0
"""The altitude the rendered column's tangent optical depth is referenced at, km."""

# Tomasko et al. (2008): the haze above 80 km has optical depth
# _TAU_COEFFICIENT * lambda**_TAU_EXPONENT (lambda in nm), with a 65 km scale height
# up to 140 km.
_TAU_COEFFICIENT = 1.012e7
_TAU_EXPONENT = -2.339
_LOW_HAZE_BASE_KM = 80.0
_LOW_HAZE_SCALE_HEIGHT_KM = 65.0

_TABLE = np.array(TITAN_HAZE_ROWS, dtype=np.float64)


@dataclass(frozen=True)
class TitanHaze:
    """Titan's haze averaged over a passband.

    Parameters:
        tangent_depth: The tangent optical depth at 140 km.
        albedo: The single-scattering albedo.
        g: The first Henyey-Greenstein term's asymmetry parameter.
        g2: The second term's asymmetry parameter.
        g2_fraction: The share of the scattered light in the second term.
    """

    tangent_depth: float
    albedo: float
    g: float
    g2: float
    g2_fraction: float


def tangent_depth_at_reference(wavelength_nm: NDArrayFloatType) -> NDArrayFloatType:
    """The haze's tangent optical depth at 140 km, at each wavelength.

    Parameters:
        wavelength_nm: Wavelengths, nm.

    Returns:
        The tangent optical depth of a line of sight grazing 140 km.
    """
    above_80 = _TAU_COEFFICIENT * np.asarray(wavelength_nm, dtype=np.float64) ** _TAU_EXPONENT
    # The extinction at 80 km is the published column over the 65 km scale height, so
    # with the 45 km scale height above 140 km the column above 80 km is 0.88 of the
    # published one; keeping the published total would put the 650 nm tangent depth
    # at 16.3 instead of 14.3, about 6 km higher at unit tangent optical depth.
    extinction_at_reference = (
        above_80
        / _LOW_HAZE_SCALE_HEIGHT_KM
        * math.exp(-(REFERENCE_ALTITUDE_KM - _LOW_HAZE_BASE_KM) / _LOW_HAZE_SCALE_HEIGHT_KM)
    )
    path_km = math.sqrt(
        2.0 * math.pi * (TITAN_MEAN_RADIUS_KM + REFERENCE_ALTITUDE_KM) * SCALE_HEIGHT_KM
    )
    depth: NDArrayFloatType = extinction_at_reference * path_km
    return depth


def effective_titan_haze(passband: Passband) -> TitanHaze:
    """Titan's haze averaged over a solar-weighted passband.

    Parameters:
        passband: The passband.

    Returns:
        The averaged haze: the optical depth averaged in its logarithm, the rest
        directly.
    """
    wavelength = passband.wavelength_nm
    weight = passband.weight
    columns = [np.interp(wavelength, _TABLE[:, 0], _TABLE[:, k]) for k in range(1, 5)]
    g, g2, fraction, albedo = (float(np.sum(weight * column)) for column in columns)
    log_depth = np.log(tangent_depth_at_reference(np.maximum(wavelength, 1.0)))
    return TitanHaze(
        tangent_depth=float(np.exp(np.sum(weight * log_depth))),
        albedo=albedo,
        g=g,
        g2=g2,
        g2_fraction=fraction,
    )


def _km_per_pixel(body: Body) -> float:
    """The body's kilometers per pixel: its own, or Titan's radius over its mean semi-axis.

    Semi-axis c takes its default, so a body that leaves it out and one that states the
    default value get the same scale.
    """
    if body.km_per_pixel is not None:
        return body.km_per_pixel
    axes = body.semi_axes_px()
    return TITAN_MEAN_RADIUS_KM / (sum(axes) / len(axes))


def resolve_model_atmosphere(
    body: Body, *, instrument: str | None, filter_name: str | None
) -> Body:
    """Replace a ``haze_model: titan`` atmosphere block with Titan's haze in explicit keys.

    A body without such a block comes back unchanged, as the same body.

    Parameters:
        body: One body of the scene.
        instrument: The scene's instrument.
        filter_name: The scene's ``detector.filter``, or None for the clear filter.

    Returns:
        The body, with its atmosphere block resolved.
    """
    atmosphere = body.atmosphere
    if atmosphere is None or atmosphere.haze_model != TITAN_HAZE_MODEL:
        return body
    haze = effective_titan_haze(solar_weighted_passband(instrument, filter_name))
    km_per_px = _km_per_pixel(body)
    resolved = replace(
        atmosphere,
        haze_model=None,
        scale_height_px=SCALE_HEIGHT_KM / km_per_px,
        tau_ref=haze.tangent_depth,
        ref_altitude_px=REFERENCE_ALTITUDE_KM / km_per_px,
        g=haze.g,
        g2=haze.g2,
        g2_fraction=haze.g2_fraction,
        albedo=haze.albedo,
    )
    return replace(body, atmosphere=resolved)


def resolved_atmosphere_params(body_params: Mapping[str, Any], resolved: Body) -> dict[str, Any]:
    """A body's ``atmosphere`` mapping with its named haze written out in the column's keys.

    The render truth records each body's scene entry with the haze it is drawn with, so a
    block that named a haze model is recorded with the column's keys in its place.

    Parameters:
        body_params: The body's scene mapping, whose ``atmosphere`` block sets the model.
        resolved: The body as :func:`resolve_model_atmosphere` resolved it.

    Returns:
        The block without ``haze_model`` and with the column's keys of the resolved haze.
    """
    assert resolved.atmosphere is not None
    kept = {key: value for key, value in body_params['atmosphere'].items() if key != 'haze_model'}
    return kept | {key: getattr(resolved.atmosphere, key) for key in HAZE_MODEL_KEYS}
